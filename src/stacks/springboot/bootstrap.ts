import { existsSync, rmSync } from "node:fs";
import path from "node:path";
import { ensureDir } from "../../utils/fsWrite.js";
import { isAvailable, runCommand } from "../../utils/runCommand.js";
import type { SpringBootAddons } from "./types.js";

/**
 * Creates the project base with Spring Initializr (start.spring.io) - Spring's own
 * project generator, and the same service the "Spring Initializr" button in every
 * IDE calls.
 *
 * Why delegate: a hand-written pom.xml pins a Spring Boot version that is correct
 * the week it is written and wrong afterwards. Initializr returns the current
 * release with a dependency set the Spring team manages, so the generated project
 * stays current without this file being maintained.
 *
 * Unlike `nest new`, there is no CLI to install: Initializr is an HTTP API that
 * returns a zip. That is the only real difference in the pattern.
 *
 * Returns false rather than throwing when it cannot be used (offline, no curl, no
 * extractor, a non-200), so the adapter falls back to its own templates and still
 * produces a working project.
 */

const INITIALIZR_URL = "https://start.spring.io/starter.zip";

/**
 * Maps this adapter's choices onto Initializr dependency ids, so the pom it
 * returns already contains everything the project needs. That avoids merging XML
 * afterwards - the reason the NestJS path merges JSON but this one does not.
 */
export function initializrDependencies(addons: SpringBootAddons): string[] {
  const deps = ["web", "validation", "actuator"];

  if (addons.dbProvider !== "none") {
    deps.push("data-jpa");
    // Flyway because a database with no migration tool is a finding `buildquick
    // check` would report on this project's own output.
    deps.push("flyway");
    deps.push(addons.dbProvider === "mysql" ? "mysql" : "postgresql");
    // H2 so the generated tests run with no database server.
    deps.push("h2");
  }
  if (addons.includeJwt) deps.push("security");

  return deps;
}

export async function bootstrapWithInitializr(projectDir: string, projectName: string, addons: SpringBootAddons, javaVersion = "21"): Promise<boolean> {
  if (!(await isAvailable("curl", path.dirname(projectDir)))) return false;

  // The starter zip has no wrapper directory - pom.xml and src/ sit at its root -
  // so it extracts straight into the project directory rather than beside it.
  ensureDir(projectDir);
  const zipPath = path.join(projectDir, "initializr.zip");
  const artifactId = projectName.toLowerCase();

  // bootVersion is deliberately not sent: omitting it asks Initializr for its
  // current default release, which is the entire point of calling it.
  const params = [
    ["type", "maven-project"],
    ["language", "java"],
    ["javaVersion", javaVersion],
    ["groupId", "com.buildquick"],
    ["artifactId", artifactId],
    ["name", projectName],
    ["packageName", `com.buildquick.${artifactId}`],
    ["dependencies", initializrDependencies(addons).join(",")],
  ];

  const download = await runCommand(
    "curl",
    ["-sS", "--fail", "--max-time", "120", "--get", ...params.flatMap(([k, v]) => ["--data-urlencode", `${k}=${v}`]), "-o", zipPath, INITIALIZR_URL],
    projectDir,
    180_000
  );
  if (!download.ok || !existsSync(zipPath)) return false;

  const extracted = await extractZip(zipPath, projectDir);
  rmSync(zipPath, { force: true });

  return extracted && existsSync(path.join(projectDir, "pom.xml"));
}

/**
 * bsdtar (macOS, Windows 10+) reads zip files, so `tar -xf` needs nothing
 * installed; `unzip` is the fallback for Linux images that ship GNU tar, which
 * does not.
 */
async function extractZip(zipPath: string, intoDir: string): Promise<boolean> {
  const viaTar = await runCommand("tar", ["-xf", zipPath], intoDir, 120_000);
  if (viaTar.ok) return true;
  const viaUnzip = await runCommand("unzip", ["-q", "-o", zipPath], intoDir, 120_000);
  return viaUnzip.ok;
}

/**
 * The files Initializr writes that this adapter replaces. Its Application class
 * and test are regenerated by the layout, and leaving both would mean two classes
 * annotated @SpringBootApplication.
 */
export function removeInitializrDefaults(projectDir: string, projectName: string): void {
  const artifactId = projectName.toLowerCase();
  const pkgPath = path.join("com", "buildquick", artifactId);
  const className = `${projectName.charAt(0).toUpperCase()}${projectName.slice(1)}Application`;

  for (const relPath of [path.join("src", "main", "java", pkgPath, `${className}.java`), path.join("src", "test", "java", pkgPath, `${className}Tests.java`)]) {
    rmSync(path.join(projectDir, relPath), { force: true });
  }
}
