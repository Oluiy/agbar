import type { Decision } from "./explain.js";

/** Renders the applicable decisions for one generated project into ARCHITECTURE.md's contents. */
export function renderArchitectureDoc(projectName: string, decisions: Decision[]): string {
  const intro = `# Architecture notes for ${projectName}\n\nGenerated by \`agbar\`. This isn't just what got built - it's why it's shaped this way. Each section below ties a real structural choice in this project to the engineering principle behind it.\n`;

  if (decisions.length === 0) {
    return `${intro}\nNo callouts for this configuration.\n`;
  }

  const sections = decisions
    .map((d) => {
      const goDeeper = d.conceptId ? `\nGo deeper: \`agbar concepts ${d.conceptId}\`\n` : "";
      return `## ${d.title}\n\n**Principle:** ${d.principle}\n\n${d.explanation}\n${goDeeper}`;
    })
    .join("\n");
  return `${intro}\n${sections}`;
}
